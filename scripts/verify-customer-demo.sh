#!/usr/bin/env bash
# Drives the release UI on an isolated emulator with a throwaway catalogue.
# Never sends checkout and refuses to run against a real backend.
set -euo pipefail

: "${ANDROID_HOME:?ANDROID_HOME is required}"
OUTPUT="${1:?screenshot output directory is required}"
PACKAGE="com.zakeleo877.saeedstore"
ADB="$ANDROID_HOME/platform-tools/adb"
[ -x "$ADB" ] || { echo 'FAIL: adb is unavailable'; exit 1; }
grep -qxF 'SUPABASE_URL=https://placeholder.invalid' local.properties || {
  echo 'FAIL: demo UI checks require the isolated placeholder backend'; exit 1;
}
SERIAL="$("$ADB" devices | awk '$1 ~ /^emulator-/ && $2 == "device" {print $1; exit}')"
[ -n "$SERIAL" ] || { echo 'FAIL: no running emulator'; exit 1; }
mkdir -p "$OUTPUT"
TREE="$(mktemp)"
trap 'rm -f "$TREE"' EXIT

# The Compose semantics tree is exported by Android's own UI Automator.
dump_ui() {
  timeout 40 "$ADB" -s "$SERIAL" shell uiautomator dump /sdcard/saeed-ui.xml >/dev/null
  timeout 20 "$ADB" -s "$SERIAL" exec-out cat /sdcard/saeed-ui.xml > "$TREE"
}
find_node() {
  python3 - "$TREE" "$1" "$2" <<'PY'
import re, sys
from xml.etree import ElementTree as ET
path, mode, wanted = sys.argv[1:]
try:
    root = ET.parse(path).getroot()
except (OSError, ET.ParseError):
    raise SystemExit(1)
for node in root.iter('node'):
    text, desc = node.get('text', ''), node.get('content-desc', '')
    matches = (mode == 'text' and text == wanted) or \
              (mode == 'desc' and desc == wanted) or \
              (mode == 'contains' and (wanted in text or wanted in desc)) or \
              (mode == 'desc-prefix' and desc.startswith(wanted))
    if not matches:
        continue
    match = re.fullmatch(r'\[(\d+),(\d+)\]\[(\d+),(\d+)\]', node.get('bounds', ''))
    if match:
        x1, y1, x2, y2 = map(int, match.groups())
        if x2 > x1 and y2 > y1:
            print((x1 + x2) // 2, (y1 + y2) // 2)
            raise SystemExit(0)
raise SystemExit(1)
PY
}
wait_node() {
  local mode="$1" label="$2" position=""
  for _ in 1 2 3 4 5 6; do
    dump_ui || true
    position="$(find_node "$mode" "$label" || true)"
    if [ -n "$position" ]; then printf '%s\n' "$position"; return 0; fi
    sleep 1
  done
  printf 'FAIL: could not find UI element: %s\n' "$label" >&2
  # This is an isolated placeholder build; log its visible semantics to make
  # a failed test diagnosable without exposing a real customer's information.
  python3 - "$TREE" >&2 <<'PY'
from xml.etree import ElementTree as ET
import sys
try:
    root = ET.parse(sys.argv[1]).getroot()
    for node in root.iter('node'):
        text, desc = node.get('text', ''), node.get('content-desc', '')
        if text or desc:
            print('text=', repr(text), 'description=', repr(desc))
except Exception as exc:
    print('Could not read the isolated UI tree:', exc)
PY
  timeout 60 "$ADB" -s "$SERIAL" exec-out screencap -p > "$OUTPUT/customer-demo-failure.png" || true
  return 1
}
tap() {
  local position
  position="$(wait_node "$1" "$2")"
  # Coordinates are generated by find_node and contain only two integers.
  read -r x y <<< "$position"
  "$ADB" -s "$SERIAL" shell input tap "$x" "$y"
}
snapshot() {
  timeout 60 "$ADB" -s "$SERIAL" exec-out screencap -p > "$OUTPUT/$1"
  [ -s "$OUTPUT/$1" ] || { echo "FAIL: empty screenshot $1"; exit 1; }
}

# Open the independent product tab and verify the test catalogue was actually seeded.
tap desc 'المنتجات'
wait_node text 'كل المنتجات' >/dev/null
size="$("$ADB" -s "$SERIAL" shell wm size | tr -d '\r' | grep -oE '[0-9]+x[0-9]+' | tail -1)"
width="${size%x*}"; height="${size#*x}"
for _ in 1 2 3 4; do
  dump_ui || true
  if find_node contains 'أداة تصفيف تجريبية' >/dev/null; then break; fi
  "$ADB" -s "$SERIAL" shell input swipe "$((width / 2))" "$((height * 3 / 4))" "$((width / 2))" "$((height / 3))" 350
  sleep 1
done
wait_node contains 'أداة تصفيف تجريبية' >/dev/null
snapshot customer-products-demo.png
printf 'PASS: product tab renders the isolated sample catalogue\n'

# Add the sample product, inspect the cart, and open checkout without submitting.
tap desc 'أضف أداة تصفيف تجريبية إلى السلة'
tap desc-prefix 'السلة'
wait_node text 'سلة المشتريات' >/dev/null
wait_node contains 'أداة تصفيف تجريبية' >/dev/null
snapshot customer-cart-demo.png
printf 'PASS: adding a sample item reaches the cart\n'
tap text 'إتمام الطلب'
wait_node contains 'الاسم الكامل' >/dev/null
wait_node contains 'رقم الهاتف' >/dev/null
snapshot customer-checkout-demo.png
printf 'PASS: checkout form opens; no order was submitted\n'

"$ADB" -s "$SERIAL" shell input keyevent 4
tap desc 'الطلبات المعلّقة'
wait_node text 'لا توجد طلبات معلّقة.' >/dev/null
printf 'PASS: pending tab opens the local send queue\n'
tap desc 'الرئيسية'
wait_node text 'تفاصيل أجمل ليومك' >/dev/null
printf 'PASS: home navigation works\n'

[ -n "$("$ADB" -s "$SERIAL" shell pidof "$PACKAGE" | tr -d '\r')" ] || {
  echo 'FAIL: the customer app stopped during navigation'; exit 1;
}
if "$ADB" -s "$SERIAL" logcat -d -s AndroidRuntime:E '*:S' | grep -q 'FATAL EXCEPTION'; then
  echo 'FAIL: Android reported a fatal exception during the UI interactions'; exit 1
fi
printf 'PASS: no crash during isolated customer interactions\n'
